#include<stdio.h>

int main()
{
	unsigned int Value = 11;
	
	printf("Value of decimal format : %d\n",Value);
	printf("Value of octal format : %o\n",Value);
	printf("Value of hexadecimal format : %x\n",Value);	
	
	return 0;
}